"""HTTP logout checks with a synthetic PHP session; no application accounts change.

Run: python tests/logout.py
Starts an isolated local PHP server and session directory. Override PHP_BINARY
when needed. No existing browser sessions or application accounts are changed.
"""
import json
import os
from pathlib import Path
import re
import subprocess
import socket
import uuid
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
PHP = os.environ.get('PHP_BINARY', 'C:/xampp/php/php.exe')
class TestDirectory:
    def __init__(self):
        self.path = ROOT / 'scratch' / ('ojtrack-logout-' + uuid.uuid4().hex)
        self.path.mkdir(mode=0o777)
        self.name = str(self.path)
    def cleanup(self):
        assert self.path.resolve().parent == (ROOT / 'scratch').resolve()
        for child in self.path.iterdir():
            child.unlink()
        self.path.rmdir()

work = TestDirectory()
session_dir = Path(work.name)
with socket.socket() as port_socket:
    port_socket.bind(('127.0.0.1', 0))
    port = port_socket.getsockname()[1]
BASE = f'http://127.0.0.1:{port}/ojtrack/'
router = session_dir / 'router.php'
app_root = str(ROOT).replace('\\', '/').replace("'", "\\'")
router.write_text("<?php $path=parse_url($_SERVER['REQUEST_URI'],PHP_URL_PATH); "
    "if(!in_array($path,['/ojtrack/logout.php','/ojtrack/student/onboarding.php'],true)){http_response_code(404);exit;} "
    f"require '{app_root}/'.substr($path,9);", encoding='utf-8')
server = subprocess.Popen([PHP, '-d', f'session.save_path={session_dir}', '-S', f'127.0.0.1:{port}', str(router)],
    cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0)
for attempt in range(50):
    try:
        with socket.create_connection(('127.0.0.1',port),timeout=0.1):
            break
    except OSError:
        time.sleep(0.1)
else:
    server.terminate()
    work.cleanup()
    raise RuntimeError('Isolated PHP server did not start')

class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None

def php(code):
    return subprocess.check_output([PHP, '-d', f'session.save_path={session_dir}', '-r', code], cwd=ROOT, text=True)

fixture = json.loads(php("require 'config/security.php'; "
    "$_SESSION['user_id']=-999999; $_SESSION['role']='student'; "
    "echo json_encode(['id'=>session_id(),'token'=>csrf_token(),'cookie'=>session_name(),"
    "'file'=>session_save_path().DIRECTORY_SEPARATOR.'sess_'.session_id()]); session_write_close();"))
opener = urllib.request.build_opener(NoRedirect)
cookie = fixture['cookie'] + '=' + fixture['id']
checks = 0

def request(path, data=None):
    payload = None if data is None else urllib.parse.urlencode(data).encode()
    req = urllib.request.Request(BASE + path, data=payload, headers={'Cookie': cookie})
    try:
        return opener.open(req, timeout=10)
    except urllib.error.HTTPError as error:
        return error

def check(ok, label):
    global checks
    if not ok:
        raise AssertionError(label)
    checks += 1

try:
    source = (ROOT / 'student/onboarding.php').read_text(encoding='utf-8')
    form = re.search(r'<form\b[^>]*action="/ojtrack/logout.php"[^>]*>(.*?)</form>', source, re.S)
    check(form is not None, 'Onboarding renders a logout form')
    check('method="POST"' in form.group(0) and 'csrf_field()' in form.group(1), 'Form sends POST and CSRF token')
    response = request('logout.php')
    check(response.status == 302 and response.headers.get('Location') == '/ojtrack/index.php', 'GET does not sign users out')
    response = request('logout.php', {'csrf_token': 'invalid-test-token'})
    check(response.status == 403, 'Invalid token rejected')
    check('-999999' in Path(fixture['file']).read_text(), 'Rejected request preserves session')
    response = request('logout.php', {'csrf_token': fixture['token']})
    check(response.status in (302, 303) and response.headers.get('Location') == '/ojtrack/login.php', 'Valid logout redirects to login')
    check('expires=' in response.headers.get('Set-Cookie', '').lower(), 'Session cookie expires')
    check(not Path(fixture['file']).exists(), 'Server session destroyed')
    response = request('student/onboarding.php')
    check(response.status == 302 and response.headers.get('Location', '').endswith('/ojtrack/login.php'), 'Old session cannot reopen onboarding')
    print(f'{checks} logout checks passed.')
finally:
    # Only remove the exact random session generated by this test.
    server.terminate()
    server.wait(timeout=5)
    work.cleanup()

